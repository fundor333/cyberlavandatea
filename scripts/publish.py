#!/usr/bin/env python3
"""Interactively publish a new version of the theme.

Flow:
  1. check you are on `main` and in sync with origin;
  2. offer to commit any uncommitted changes;
  3. ask for the release type (hotfix / minor / major) and show the resulting tag;
  4. verify the exampleSite still builds (`make build`);
  5. push to origin/main -> CI and Pages run (the site is rebuilt);
  6. dispatch the `release.yml` workflow with the chosen bump, which updates
     CHANGELOG.md and package.json, creates the tag and the GitHub Release;
  7. follow the run and, once it finishes, pull the release commit.

Usage: make publish   (or: python3 scripts/publish.py [--dry-run])
"""

from __future__ import annotations

import argparse
import calendar
import json
import os
import shutil
import subprocess
import sys
import time

BRANCH = "main"
WORKFLOW = "release.yml"
BUMPS = {
    "1": ("hotfix", "bug fixes only, nothing new"),
    "2": ("minor", "new backwards-compatible features"),
    "3": ("major", "breaking changes"),
}
CONVENTIONAL_TYPES = ("feat", "fix", "style", "refactor", "perf", "docs", "chore", "build", "ci", "test")

# Invoked from the Makefile, MAKE is the real make binary. Calling the
# /usr/bin/make shim from an x86_64 (Rosetta) Python fails inside xcrun.
MAKE = os.environ.get("MAKE", "make")

DRY_RUN = False


# --- helpers -------------------------------------------------------------

def die(msg: str) -> None:
    print(f"\n✗ {msg}", file=sys.stderr)
    sys.exit(1)


def out(*cmd: str) -> str:
    """Run a read-only command and return its stdout."""
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        die(f"command failed: {' '.join(cmd)}\n{res.stderr.strip()}")
    return res.stdout.strip()


def run(*cmd: str, mutating: bool = True) -> None:
    """Run a command showing its output; in dry-run, skip the ones that change state."""
    print(f"  $ {' '.join(cmd)}")
    if DRY_RUN and mutating:
        print("    (dry-run: skipped)")
        return
    if subprocess.run(cmd).returncode != 0:
        die(f"command failed: {' '.join(cmd)}")


def ask(prompt: str, default: str | None = None) -> str:
    suffix = f" [{default}]" if default else ""
    try:
        answer = input(f"{prompt}{suffix}: ").strip()
    except (EOFError, KeyboardInterrupt):
        die("aborted.")
    return answer or (default or "")


def confirm(prompt: str, default: bool = True) -> bool:
    hint = "Y/n" if default else "y/N"
    answer = ask(f"{prompt} ({hint})").lower()
    if not answer:
        return default
    return answer in ("y", "yes")


def step(title: str) -> None:
    print(f"\n▸ {title}")


# --- logic ---------------------------------------------------------------

def last_tag() -> str:
    res = subprocess.run(["git", "describe", "--tags", "--abbrev=0"], capture_output=True, text=True)
    return res.stdout.strip() if res.returncode == 0 else "v0.0.0"


def next_version(tag: str, bump: str) -> str:
    major, minor, patch = (int(x) for x in tag.lstrip("v").split("."))
    if bump == "major":
        return f"{major + 1}.0.0"
    if bump == "minor":
        return f"{major}.{minor + 1}.0"
    return f"{major}.{minor}.{patch + 1}"


def check_prerequisites() -> None:
    step("Preflight checks")
    for tool in ("git", "gh"):
        if not shutil.which(tool):
            die(f"`{tool}` not found in PATH.")
    if subprocess.run(["gh", "auth", "status"], capture_output=True).returncode != 0:
        die("gh is not authenticated: run `gh auth login`.")

    branch = out("git", "rev-parse", "--abbrev-ref", "HEAD")
    if branch != BRANCH:
        die(f"you are on branch `{branch}`: releases are cut from `{BRANCH}`.")
    print(f"  branch: {branch} ✓")


def handle_uncommitted() -> None:
    status = out("git", "status", "--porcelain")
    if not status:
        print("  working tree clean ✓")
        return

    print("  There are uncommitted changes:\n")
    print(out("git", "status", "--short"))
    print()
    if not confirm("Commit all of them now?"):
        die("commit or stash your changes, then run again.")

    print(f"  Conventional Commit types: {', '.join(CONVENTIONAL_TYPES)}")
    print("  (the type ends up in the CHANGELOG generated by git-cliff)")
    while True:
        message = ask("Commit message (e.g. `fix: correct the mobile menu`)")
        if message.split(":")[0].split("(")[0].rstrip("!") in CONVENTIONAL_TYPES and ":" in message:
            break
        if message and confirm("The message does not follow Conventional Commits, use it anyway?", default=False):
            break
    run("git", "add", "-A")
    run("git", "commit", "-m", message)


def sync_with_remote() -> None:
    step("Syncing with origin")
    run("git", "fetch", "origin", BRANCH, "--tags", mutating=False)
    behind = int(out("git", "rev-list", "--count", f"HEAD..origin/{BRANCH}"))
    if behind:
        print(f"  origin/{BRANCH} has {behind} commit(s) you don't have locally.")
        if not confirm("Run `git pull --rebase`?"):
            die("bring your branch in sync with origin, then run again.")
        run("git", "pull", "--rebase", "origin", BRANCH)
    else:
        print("  up to date with origin ✓")


def show_pending_commits(tag: str) -> None:
    step(f"Commits going into the release (since {tag})")
    log = out("git", "log", f"{tag}..HEAD", "--oneline", "--no-decorate")
    if not log:
        if DRY_RUN:
            print("  (dry-run: no commits yet, continuing anyway)")
            return
        die(f"no commits since {tag}: nothing to release.")
    for line in log.splitlines():
        print(f"  • {line}")


def choose_bump(tag: str) -> tuple[str, str]:
    step("Release type")
    for key, (name, desc) in BUMPS.items():
        print(f"  {key}) {name:<7} → v{next_version(tag, name):<9} {desc}")
    while True:
        choice = ask("Choice (1/2/3 or name)").lower()
        for key, (name, _) in BUMPS.items():
            if choice in (key, name):
                return name, next_version(tag, name)
        print("  invalid choice.")


def latest_release_run_id(after: float) -> str | None:
    """Find the release.yml run started after `after` (epoch timestamp)."""
    raw = out(
        "gh", "run", "list", f"--workflow={WORKFLOW}", "--event=workflow_dispatch",
        "--limit=5", "--json", "databaseId,createdAt",
    )
    for run_info in json.loads(raw or "[]"):
        created = calendar.timegm(time.strptime(run_info["createdAt"], "%Y-%m-%dT%H:%M:%SZ"))
        if created >= after - 5:
            return str(run_info["databaseId"])
    return None


def dispatch_release(bump: str) -> None:
    step(f"Dispatching the {WORKFLOW} workflow (bump={bump})")
    started = time.time()
    run("gh", "workflow", "run", WORKFLOW, "-f", f"bump={bump}")
    if DRY_RUN:
        return

    run_id = None
    for _ in range(15):
        time.sleep(2)
        run_id = latest_release_run_id(started)
        if run_id:
            break
    if not run_id:
        die("workflow dispatched but the run could not be found: check `gh run list`.")

    print(f"  run {run_id} — watching:")
    if subprocess.run(["gh", "run", "watch", run_id, "--exit-status"]).returncode != 0:
        die(f"the release workflow failed: `gh run view {run_id} --log-failed`.")


def main() -> None:
    global DRY_RUN
    sys.stdout.reconfigure(line_buffering=True)
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="show what would happen without committing, pushing or releasing")
    parser.add_argument("--skip-build", action="store_true", help="skip the `make build` check")
    args = parser.parse_args()
    DRY_RUN = args.dry_run

    print("═══ Publishing CyberLavandaTea ═══" + ("  (dry-run)" if DRY_RUN else ""))

    check_prerequisites()
    handle_uncommitted()
    sync_with_remote()

    tag = last_tag()
    show_pending_commits(tag)
    bump, version = choose_bump(tag)

    step("Summary")
    print(f"  current version : {tag}")
    print(f"  new version     : v{version} ({bump})")
    print(f"  actions         : local build → push {BRANCH} (CI + Pages) → release.yml → tag + GitHub Release")
    if not confirm("Proceed?"):
        die("aborted.")

    if not args.skip_build:
        step("Checking the exampleSite build")
        run(MAKE, "build", mutating=False)

    step(f"Pushing to origin/{BRANCH} (triggers CI and Pages)")
    run("git", "push", "origin", BRANCH)

    dispatch_release(bump)

    step("Pulling the release commit into the local repository")
    run("git", "pull", "--rebase", "--tags", "origin", BRANCH)

    repo = out("gh", "repo", "view", "--json", "url", "--jq", ".url")
    print(f"\n✓ Released v{version}: {repo}/releases/tag/v{version}")


if __name__ == "__main__":
    main()
